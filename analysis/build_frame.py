"""One table of every abstract (human, Claude, ChatGPT) with metadata and features.

Usage (from the repo root):
  python -m analysis.build_frame

Inputs:
  data/processed/ismir_2020_2025_v1.jsonl   human abstracts and metadata
  data/interim/synthetic/{paper_id}.json    Claude abstracts (analysis.generate)
  data/random_5_abstracts_gpt.txt           ChatGPT abstracts, written by hand in the ChatGPT app,
                                            blocks headed "===== {year} | {paper_id} ====="

Outputs (data/processed/):
  abstracts_v1.csv   one row per abstract (1,340): metadata, source, model, text and every feature
  papers_v1.csv      one row per paper (655): metadata and the three abstract columns (wide)
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

import pandas as pd

from analysis.features import features
from analysis.generate import strip_label
from parsing.models import read_jsonl

JSONL = Path("data/processed/ismir_2020_2025_v1.jsonl")
CLAUDE_DIR = Path("data/interim/synthetic")
GPT_TXT = Path("data/random_5_abstracts_gpt.txt")
OUT_DIR = Path("data/processed")

HUMAN, CLAUDE, GPT = "abstract_human", "abstract_synthetic_claude", "abstract_synthetic_gpt"
SOURCES = (HUMAN, CLAUDE, GPT)
GPT_MODEL = "chatgpt-app"  # generated by hand in the ChatGPT app; the exact model version was not recorded

GPT_HEADER = re.compile(r"^=+\s*(\d{4})\s*\|\s*(\d{4}_\d{6})\s*=+\s*$", re.MULTILINE)
# Markdown emphasis that LLMs put in plain text (*linmdtw*, **bold**). Only paired markers around a span are removed,
# so format names such as "**kern" stay as they are.
EMPHASIS = re.compile(r"(?<![\w*])(\*{1,2})(?![\s*])(.+?)(?<![\s*])\1(?![\w*])")


# A word-count note the model adds at the end: "(≈160 words)", "*(Word count: ~183)*". Only at the very end, so
# "(2014)" or "(156)" inside the text are kept.
WORD_COUNT_NOTE = re.compile(r"\s*\**\(\s*(?:word count\s*:?\s*)?[≈~]?\s*\d+\s*(?:words)?\s*\)\**\s*$", re.IGNORECASE)


def clean_synthetic(text: str) -> str:
    """Remove generation artifacts from an LLM abstract. Applied to both synthetic sources, never to human text.

    - If the answer holds several versions separated by '---' (2020_000080: a first draft, a comment, then a longer
      version), keep the last one.
    - Leading headings and an "Abstract" label (same rule as analysis.generate).
    - A trailing word-count note.
    - Paired markdown emphasis (*title*, **bold**).
    """
    text = re.split(r"\n\s*---+\s*\n", text)[-1]
    text = re.split(r"^[#*\s]*abstract[*:.\s]*$", text, flags=re.IGNORECASE | re.MULTILINE)[-1]  # comment before it
    text = strip_label(text)
    text = WORD_COUNT_NOTE.sub("", text)
    return EMPHASIS.sub(r"\2", text).strip()


def read_gpt(path: Path) -> dict[str, tuple[int, str]]:
    """paper_id -> (year in the header, abstract)."""
    text = path.read_text(encoding="utf-8")
    headers = list(GPT_HEADER.finditer(text))
    out = {}
    for header, nxt in zip(headers, headers[1:] + [None]):
        body = text[header.end(): nxt.start() if nxt else len(text)].strip()
        year, paper_id = int(header.group(1)), header.group(2)
        if paper_id in out:
            raise SystemExit(f"{path}: {paper_id} appears twice")
        if not body:
            raise SystemExit(f"{path}: {paper_id} has no abstract")
        out[paper_id] = (year, body)
    return out


def read_claude(directory: Path) -> dict[str, dict]:
    return {p.stem: json.loads(p.read_text(encoding="utf-8")) for p in sorted(directory.glob("*.json"))}


def build() -> tuple[pd.DataFrame, pd.DataFrame]:
    papers = {p.paper_id: p for p in read_jsonl(JSONL)}
    claude = read_claude(CLAUDE_DIR)
    gpt = read_gpt(GPT_TXT)

    for name, ids in (("Claude", claude), ("ChatGPT", gpt)):
        if unknown := sorted(set(ids) - set(papers)):
            raise SystemExit(f"{name} abstracts for unknown paper_ids: {', '.join(unknown)}")
    if wrong := [pid for pid, (year, _) in gpt.items() if papers[pid].year != year]:
        raise SystemExit(f"ChatGPT header year does not match the paper's year: {', '.join(wrong)}")

    rows, wide = [], []
    for pid, paper in sorted(papers.items()):
        meta = {"paper_id": pid, "year": paper.year, "title": paper.title, "authors": paper.authors,
                "n_authors": len([a for a in paper.authors.split(",") if a.strip()]), "doi": paper.doi}
        texts = {
            HUMAN: (paper.abstract, "human"),
            CLAUDE: (clean_synthetic(claude[pid]["abstract"]), claude[pid]["model"]) if pid in claude else None,
            GPT: (clean_synthetic(gpt[pid][1]), GPT_MODEL) if pid in gpt else None,
        }
        wide.append({**meta, **{src: (t[0] if t else None) for src, t in texts.items()},
                     "target_words": len(paper.abstract.split())})
        for src, value in texts.items():
            if value and value[0]:
                rows.append({**meta, "source": src, "model": value[1], "text": value[0]})

    abstracts = pd.DataFrame(rows)
    feats = pd.DataFrame([features(t) for t in abstracts.text])
    abstracts = pd.concat([abstracts, feats], axis=1)
    abstracts["source"] = pd.Categorical(abstracts.source, categories=SOURCES)
    return abstracts, pd.DataFrame(wide)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out-dir", type=Path, default=OUT_DIR)
    args = parser.parse_args()

    abstracts, papers = build()
    args.out_dir.mkdir(parents=True, exist_ok=True)
    for name, frame in (("abstracts_v1", abstracts), ("papers_v1", papers)):
        frame.to_csv(args.out_dir / f"{name}.csv", index=False)
    print(abstracts.groupby(["year", "source"], observed=True).size().unstack().to_string())
    print(f"{len(abstracts)} abstracts, {len(papers)} papers -> {args.out_dir}")


if __name__ == "__main__":
    main()
